from dataclasses import dataclass
from pathlib import Path

from sailpack import export_load_case_mapping_seed, export_reference_values_seed
from sailpack.export_load_case_mapping_seed import (
    AmbiguousLoadCases,
    find_ambiguous_load_cases,
)
from sailpack.max_loads import (
    clamp_targets_to_thresholds,
    read_max_loads,
    write_conflicts,
)
from sailpack.parse import parse_directory
from sailpack.seed_utils import (
    build_load_case_records,
    extract_reference_values,
    read_reference_values_mapping,
)


@dataclass(frozen=True)
class SeedExport:
    load_case_count: int
    reference_count: int
    conflict_count: int
    load_case_mapping_count: int
    ambiguous_load_cases: list[AmbiguousLoadCases]


def render_sql(reference_values_sql: str, load_case_mappings_sql: str) -> str:
    # One transaction: the reference values part deletes the load cases, which the mappings reference.
    return f"""-- Generated by src/sailpack/export_seed.py
-- Uses jsonb_to_recordset and resolves sail_set_id from sail abbreviations.

BEGIN;

{reference_values_sql}
{load_case_mappings_sql}
COMMIT;
"""


def export_seed_sql(
    input_source: Path,
    mapping_csv: str,
    max_loads_csv: str,
    output_sql: Path,
    conflicts_output: Path,
) -> SeedExport:
    sailpack_data = parse_directory(input_source)
    reference_values = extract_reference_values(
        sailpack_data, read_reference_values_mapping(mapping_csv)
    )
    max_loads = read_max_loads(max_loads_csv)
    targets, conflicts = clamp_targets_to_thresholds(reference_values, max_loads)
    load_case_records = build_load_case_records(sailpack_data)
    reference_records = export_reference_values_seed.build_reference_records(targets)
    mapping_records = export_load_case_mapping_seed.build_records(load_case_records)

    sql = render_sql(
        export_reference_values_seed.render_sql(
            load_case_records,
            reference_records,
            export_reference_values_seed.build_threshold_records(max_loads),
        ),
        export_load_case_mapping_seed.render_sql(mapping_records),
    )
    output_sql.write_text(sql, encoding="utf-8")
    write_conflicts(conflicts, conflicts_output)

    return SeedExport(
        load_case_count=len(load_case_records),
        reference_count=len(reference_records),
        conflict_count=len(conflicts),
        load_case_mapping_count=len(mapping_records),
        ambiguous_load_cases=find_ambiguous_load_cases(load_case_records),
    )
